export function translate(
  language: Language,
  key: TranslationKey,
  params?: Record<string, string | number>
): string {
  const dict = TRANSLATIONS[language] || TRANSLATIONS[DEFAULT_LANGUAGE];
  let template = dict[key] ?? TRANSLATIONS[DEFAULT_LANGUAGE][key] ?? key;
  if (params) {
    for (const [paramKey, val] of Object.entries(params)) {
      template = template.replace(new RegExp(`\\{${paramKey}\\}`, 'g'), String(val));
    }
  }
  return template;
}

export function resolveStoredLanguage(storage?: Pick<Storage, 'getItem'> | null): Language {
  try {
    const store = storage ?? (typeof window !== 'undefined' ? window.localStorage : null);
    const saved = store?.getItem(LANGUAGE_STORAGE_KEY);
    if (isSupportedLanguage(saved)) {
      return saved;
    }
  } catch {
    // Ignore storage access errors in restricted/SSR contexts
  }
  return DEFAULT_LANGUAGE;
}

export function persistLanguage(language: Language, storage?: Pick<Storage, 'setItem'> | null): void {
  try {
    const store = storage ?? (typeof window !== 'undefined' ? window.localStorage : null);
    store?.setItem(LANGUAGE_STORAGE_KEY, language);
  } catch {
    // Ignore storage errors
  }
}

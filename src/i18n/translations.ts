export type Language = 'en' | 'ar' | 'fr';

export interface LanguageOption {
  code: Language;
  label: string;
  dir: 'ltr' | 'rtl';
  locale: string;
}

export const DEFAULT_LANGUAGE: Language = 'en';
export const LANGUAGE_STORAGE_KEY = 'devnapp_erp_language';

/**
 * Exact language order required:
 * 1. English (default)
 * 2. Arabic ("العربية")
 * 3. French ("Français")
 */
export const SUPPORTED_LANGUAGES: LanguageOption[] = [
  { code: 'en', label: 'English', dir: 'ltr', locale: 'en-US' },
  { code: 'ar', label: 'العربية', dir: 'rtl', locale: 'ar-MA' },
  { code: 'fr', label: 'Français', dir: 'ltr', locale: 'fr-FR' },
];

export function isSupportedLanguage(val: unknown): val is Language {
  return val === 'en' || val === 'ar' || val === 'fr';
}

export function getDirection(lang: Language): 'ltr' | 'rtl' {
  return lang === 'ar' ? 'rtl' : 'ltr';
}

export function getLocale(lang: Language): string {
  return SUPPORTED_LANGUAGES.find((l) => l.code === lang)?.locale || 'en-US';
}

